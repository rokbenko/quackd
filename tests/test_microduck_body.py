"""A body of the Microduck's family is data, and two of them share one set of verbs and one wire.

`tests/test_jsonrpc.py` and `tests/test_huebot.py` hold each robot to what it does. This holds what
putting them over one package could have broken: every description each can give, what a body with
less is offered, and the line between what the family knows and what only one of its bodies claims.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

import quackd_huebot
import quackd_microduck
from quackd.transport.base import Intent
from quackd_huebot import upstream_api as huebot_api
from quackd_huebot.body import HUEBOT
from quackd_microduck.body import MICRODUCK
from quackd_microduck.transports.jsonrpc_unix import CAMERA_FPS, JsonRpcUnixTransport
from quackd_microduck.verbs import verbs_for
from tests.golden.manifest_digests import GOLDEN, digests

REPO = Path(__file__).resolve().parent.parent


def test_every_description_either_body_can_give_is_the_one_it_gave() -> None:
    """A digest changes with anything a pilot or a peer reads off a manifest, and a LAN announce
    carries it, so a refactor of the family that changed one would have changed what a robot says
    it is.
    Every backend, with and without a camera, over what a connection can settle. A manifest meant
    to change is regenerated by hand, with why in the commit (`golden/manifest_digests.py`)."""
    assert digests() == json.loads(GOLDEN.read_text(encoding="utf-8"))


def test_a_body_is_offered_only_the_verbs_it_declares_in_the_familys_order() -> None:
    """The order is the manifest's, and a digest reads it, so it is the family's whoever asks."""
    family = list(verbs_for(MICRODUCK))
    assert family[:3] == ["sit", "stand", "kick"]
    assert list(verbs_for(HUEBOT)) == [verb for verb in family if verb in HUEBOT.verbs]
    assert set(verbs_for(MICRODUCK)) == MICRODUCK.verbs
    assert set(verbs_for(HUEBOT)) == HUEBOT.verbs
    assert not {"grab", "gaze", "watch", "explore", "find"} & HUEBOT.verbs


def test_a_verb_speaks_for_the_body_it_was_bound_to() -> None:
    """One function behind each, so a line a pilot acts on can only be right by being told whose
    it is. Huebot's own description of its kick says what nobody has measured."""
    assert "Nobody has measured" in verbs_for(HUEBOT)["kick"].description
    assert "Nobody has measured" not in verbs_for(MICRODUCK)["kick"].description
    conditions = {
        body.name: quackd_microduck.conditions_for(body)["standing"] for body in (MICRODUCK, HUEBOT)
    }
    from quackd.transport.base import DuckState

    sitting = DuckState(posture="sitting")
    assert conditions["microduck"](sitting) == "the duck is sitting; run stand first"
    assert conditions["huebot"](sitting) == "Huebot is sitting; run stand first"


async def test_a_mock_is_not_kinder_than_its_robot() -> None:
    """Huebot's mock offers what a Huebot offers: no place verb, no head and no map, whatever the
    Microduck's mock scripts."""
    manifest = await quackd_huebot.make("mock").connect()
    assert manifest.sensors == ["camera", "tof", "microphone"]
    assert not {
        "map",
        "mark_place",
        "go_to_place",
        "gaze",
        "watch",
        "explore",
        "find",
        "grab",
    } & set(manifest.verb_names())
    duck = await quackd_microduck.make("mock").connect()
    assert {"map", "mark_place", "gaze", "grab"} <= set(duck.verb_names())


@pytest.mark.parametrize("url", ["http://127.0.0.1:9/frame", "https://huebot.local/frame"])
def test_a_frame_url_on_a_body_with_no_mediad_is_somebodys_snapshot_server(url: str) -> None:
    """On the Microduck `/frame` is mediad's own route, whose picture is upright and taken after
    the request. On a robot with no mediad a URL of that shape promises neither, so a frame from
    it is not one `watch` or a slow camera's steering may trust, and no lens is assumed from it."""
    hue = JsonRpcUnixTransport("tcp://127.0.0.1:1", body=HUEBOT, camera_url=url)
    assert hue.frames_upright is False
    assert hue.frame_period_s is None
    assert hue.frame_taken_at() is None
    assert hue.camera_fps == CAMERA_FPS
    assert hue.camera_fov_assumed is None
    duck = JsonRpcUnixTransport("tcp://127.0.0.1:1", camera_url=url)
    assert duck.frames_upright is True


def test_a_body_with_no_map_reports_none_to_doctor() -> None:
    """`doctor` prints a row for what became of a robot's map, and a robot that has none has no
    row, where a transport shared with one that does would otherwise say `not probed`."""
    assert JsonRpcUnixTransport("tcp://127.0.0.1:1", body=HUEBOT).mapd_report() is None
    assert JsonRpcUnixTransport("tcp://127.0.0.1:1").mapd_report() == {"state": "not probed"}


async def test_a_body_with_no_pose_or_gaze_is_sent_neither() -> None:
    """Refused before anything is written, so neither needs a link."""
    hue = JsonRpcUnixTransport("tcp://127.0.0.1:1", body=HUEBOT)
    pose = await hue.send_intent(Intent(kind="pose", params={"z": 0.1}))
    assert not pose.accepted and "no upstream mapping" in (pose.reason or "")
    look = await hue.send_intent(Intent.look(1.0, 0.0, 0.0))
    assert not look.accepted and look.reason == HUEBOT.look_refused


def test_nothing_of_the_family_spells_a_claim_about_one_of_its_bodies() -> None:
    """Huebot's maker's word is Huebot's. The family's package is scanned here because the
    containment test in `tests/test_upstream_api.py` scans a package and the core and no sibling,
    and this one sibling now runs that package's code. Nor does the family import its bodies: a
    body names its family, and the Microduck installs with no Huebot."""
    claims = [name for name in vars(huebot_api) if name.startswith("SHIM_")]
    assert len(claims) >= 5, claims
    package = REPO / "adapters" / "microduck" / "src" / "quackd_microduck"
    for path in package.rglob("*.py"):
        said = path.read_text(encoding="utf-8")
        assert "SHIM_" not in said, path
        assert "import quackd_huebot" not in said and "from quackd_huebot" not in said, path


def test_huebot_reads_the_protocol_the_microduck_reads_by_construction() -> None:
    """Imported and not copied, so a re-pin moves both, and only what is Huebot's is its own: its
    maker's refs, and what its lines say a label means."""
    from quackd_microduck import upstream_api as up

    for name in ("HELLO", "ROBOT_MOVE", "API_VERSION", "API_FLOOR", "MOVE_ECHO", "DEADMAN"):
        assert getattr(huebot_api, name) is getattr(up, name), name
    assert huebot_api.STAND_UP_RPC is not up.STAND_UP_RPC
    assert set(huebot_api.NOT_STANDING_LABELS) == set(up.NOT_STANDING_LABELS)
    assert "duck" not in " ".join(huebot_api.NOT_STANDING_LABELS.values())
